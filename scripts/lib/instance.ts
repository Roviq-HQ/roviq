export type PortVar = keyof typeof PORT_BASES;
export type InstancePorts = Record<PortVar, number>;

export const PORT_VARS = Object.keys(PORT_BASES) as PortVar[];

function isPortVar(key: string): key is PortVar {
  return key in PORT_BASES;
}

/** 20 is the smallest offset with no port shared between any two slots in 0..MAX_SLOT. */
export const SLOT_STEP = 20;
export const MAX_SLOT = 4;

const BLOCK_START = '# >>> roviq instance (generated by scripts/dev-instance.ts, do not edit)';
const BLOCK_END = '# <<< roviq instance';

export function assertSlot(slot: number): void {
  if (!Number.isInteger(slot) || slot < 0 || slot > MAX_SLOT) {
    throw new Error(`Instance slot must be an integer from 0 to ${MAX_SLOT}, got "${slot}"`);
  }
}

export function portsForSlot(slot: number): InstancePorts {
  assertSlot(slot);
  const ports = {} as InstancePorts;
  for (const name of PORT_VARS) {
    ports[name] = PORT_BASES[name] + slot * SLOT_STEP;
  }
  return ports;
}

/** Slot 0 keeps the project names the stack has always used, so its volumes survive. */
export function composeProjectsForSlot(slot: number): { dev: string; e2e: string } {
  assertSlot(slot);
  return slot === 0
    ? { dev: 'docker', e2e: 'roviq-e2e' }
    : { dev: `roviq-${slot}`, e2e: `roviq-e2e-${slot}` };
}

function portOwners(): Map<number, PortVar> {
  const owners = new Map<number, PortVar>();
  for (let slot = 0; slot <= MAX_SLOT; slot++) {
    const ports = portsForSlot(slot);
    for (const name of PORT_VARS) {
      owners.set(ports[name], name);
    }
  }
  return owners;
}

function stripInstanceBlock(lines: string[]): string[] {
  const start = lines.indexOf(BLOCK_START);
  const end = lines.indexOf(BLOCK_END);
  if (start === -1 || end === -1 || end < start) return lines;
  const before = lines.slice(0, start);
  // The block is written with one blank separator line above it.
  if (before.at(-1) === '') before.pop();
  return [...before, ...lines.slice(end + 1)];
}

/**
 * Re-targets a `.env` file at `slot`. Works from any slot's file, so it is safe to re-run:
 * ports are recognised by value across every slot, then mapped to the target slot.
 */
export function rewriteEnvForSlot(content: string, slot: number): string {
  const ports = portsForSlot(slot);
  const owners = portOwners();
  const trailingNewline = content.endsWith('\n');
  const lines = stripInstanceBlock(content.replace(/\n$/, '').split('\n'));
  const assignedInPlace = new Set<PortVar>();

  const rewritten = lines.map((line) => {
    if (line.trimStart().startsWith('#')) return line;

    const assignment = /^([A-Z0-9_]+)=(\d+)\s*$/.exec(line);
    const key = assignment?.[1];
    if (key && isPortVar(key)) {
      assignedInPlace.add(key);
      return `${key}=${ports[key]}`;
    }

    return line.replace(
      /((?:localhost|127\.0\.0\.1):)(\d{2,5})\b/g,
      (match, host: string, port: string) => {
        const owner = owners.get(Number(port));
        return owner ? `${host}${ports[owner]}` : match;
      },
    );
  });

  if (slot > 0) {
    const projects = composeProjectsForSlot(slot);
    rewritten.push(
      '',
      BLOCK_START,
      `ROVIQ_INSTANCE=${slot}`,
      `ROVIQ_COMPOSE_PROJECT=${projects.dev}`,
      `ROVIQ_E2E_COMPOSE_PROJECT=${projects.e2e}`,
      ...PORT_VARS.filter((name) => !assignedInPlace.has(name)).map(
        (name) => `${name}=${ports[name]}`,
      ),
      BLOCK_END,
    );
  }

  return rewritten.join('\n') + (trailingNewline ? '\n' : '');
}

/** Slot recorded in a `.env` file; 0 when the file has no instance block. */
export function slotFromEnv(content: string): number {
  const match = /^ROVIQ_INSTANCE=(\d+)\s*$/m.exec(content);
  return match?.[1] ? Number(match[1]) : 0;
}
